//! Rendering of `docs/FUNCTIONS.md`: the port status of every WarpLib function.
//!
//! The inventory (`docs/warplib-inventory.tsv`, one `name<TAB>JavaClass` per line) was
//! extracted from Warp 10's `WarpScriptLib.java` static registration block at the reference
//! revision. The registry is the list of function names known to the Rust runtime.

use std::collections::BTreeSet;
use std::fmt::Write as _;

/// One inventory line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InventoryEntry {
    /// WarpScript name of the function (e.g. `BUCKETIZE`, `mapper.sum`).
    pub name: String,
    /// Java class implementing it in Warp 10.
    pub class: String,
}

/// Parse the TSV inventory. Blank lines and lines starting with `#` are ignored.
pub fn parse_inventory(text: &str) -> Vec<InventoryEntry> {
    text.lines()
        .map(str::trim_end)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(|line| {
            let (name, class) = line.split_once('\t').unwrap_or((line, ""));
            InventoryEntry {
                name: name.to_owned(),
                class: class.to_owned(),
            }
        })
        .collect()
}

/// Group label used to organise the table.
pub fn group_of(name: &str) -> &'static str {
    match name.split_once('.').map(|(prefix, _)| prefix) {
        Some("mapper") => "Mappers",
        Some("reducer") => "Reducers",
        Some("bucketizer") => "Bucketizers",
        Some("filter") => "Filters",
        Some("op") => "N-ary operators",
        Some("filler") => "Fillers",
        _ => "Functions",
    }
}

/// Render the markdown document.
pub fn render(inventory_text: &str, registered: &[&str]) -> String {
    let inventory = parse_inventory(inventory_text);
    let registered: BTreeSet<&str> = registered.iter().copied().collect();
    let total = inventory.len();
    let ported = inventory
        .iter()
        .filter(|e| registered.contains(e.name.as_str()))
        .count();
    let inventory_names: BTreeSet<&str> = inventory.iter().map(|e| e.name.as_str()).collect();
    let extras: Vec<&str> = registered
        .iter()
        .copied()
        .filter(|n| !inventory_names.contains(n))
        .collect();

    let mut out = String::new();
    out.push_str("# WarpLib port status\n\n");
    out.push_str("_Generated by `cargo xtask functions` — do not edit by hand._\n\n");
    let percent = if total == 0 {
        100.0
    } else {
        (ported as f64) * 100.0 / (total as f64)
    };
    let _ = writeln!(
        out,
        "**{ported} / {total} functions ported ({percent:.1} %).**\n"
    );
    out.push_str("Reference: Warp 10 `WarpScriptLib.java` at revision `b5764364679f6ccc40a23632e352d134fab1c2eb`.\n\n");

    let groups = [
        "Functions",
        "Mappers",
        "Reducers",
        "Bucketizers",
        "Filters",
        "N-ary operators",
        "Fillers",
    ];
    for group in groups {
        let entries: Vec<&InventoryEntry> = inventory
            .iter()
            .filter(|e| group_of(&e.name) == group)
            .collect();
        if entries.is_empty() {
            continue;
        }
        let done = entries
            .iter()
            .filter(|e| registered.contains(e.name.as_str()))
            .count();
        let _ = writeln!(out, "## {group} ({done} / {})\n", entries.len());
        out.push_str("| Function | Warp 10 class | Status |\n|---|---|---|\n");
        for entry in entries {
            let status = if registered.contains(entry.name.as_str()) {
                "✅ ported"
            } else {
                "❌ todo"
            };
            let _ = writeln!(
                out,
                "| `{}` | `{}` | {status} |",
                escape(&entry.name),
                entry.class
            );
        }
        out.push('\n');
    }

    if !extras.is_empty() {
        out.push_str("## Registered in Rust but absent from the reference inventory\n\n");
        for name in extras {
            let _ = writeln!(out, "- `{}`", escape(name));
        }
        out.push('\n');
    }
    out
}

fn escape(name: &str) -> String {
    name.replace('|', "\\|")
}
