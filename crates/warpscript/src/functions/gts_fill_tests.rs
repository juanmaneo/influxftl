const G: &str = r"NEWGTS 'c' RENAME 30 NaN NaN NaN 3 ADDVALUE 50 48.0 -4.5 100 5 ADDVALUE 80 NaN NaN 200 8 ADDVALUE [ SWAP bucketizer.last 100 10 10 ] BUCKETIZE 0 GET";
const D: &str = r"NEWGTS 'd' RENAME 30 NaN NaN NaN 3.5 ADDVALUE 50 48.0 -4.5 100 5.0 ADDVALUE 80 40.0 2.0 200 8.25 ADDVALUE [ SWAP bucketizer.last 100 10 10 ] BUCKETIZE 0 GET";
const U6: &str = r"NEWGTS 'u' RENAME 10 NaN NaN NaN 1.0 ADDVALUE 20 1.0 1.0 7 2.0 ADDVALUE 40 2.0 3.0 9 4.0 ADDVALUE 70 NaN NaN NaN 1.0 ADDVALUE 75 NaN NaN NaN 2.0 ADDVALUE 90 NaN NaN NaN 3.0 ADDVALUE";
const U4: &str = r"NEWGTS 'u' RENAME 10 NaN NaN NaN 1.0 ADDVALUE 20 1.0 1.0 7 2.0 ADDVALUE 40 2.0 3.0 9 4.0 ADDVALUE 70 NaN NaN NaN 1.0 ADDVALUE";
const UL: &str = r"NEWGTS 'u' RENAME { 'k' 'v' } RELABEL 10 NaN NaN NaN 1.0 ADDVALUE 20 1.0 1.0 7 2.0 ADDVALUE 40 2.0 3.0 9 4.0 ADDVALUE 70 NaN NaN NaN 1.0 ADDVALUE";
const V4: &str = r"NEWGTS 'v' RENAME 5 NaN NaN NaN 1.0 ADDVALUE 20 NaN NaN NaN 5.0 ADDVALUE 30 NaN NaN NaN 6.0 ADDVALUE 100 NaN NaN NaN 9.0 ADDVALUE";
const V3: &str = r"NEWGTS 'v' RENAME 5 NaN NaN NaN 1.0 ADDVALUE 20 NaN NaN NaN 5.0 ADDVALUE 30 NaN NaN NaN 6.0 ADDVALUE";
const WL: &str = r"NEWGTS 'w' RENAME 10 1.0 1.0 NaN 1.0 ADDVALUE 20 2.0 2.5 NaN 2.0 ADDVALUE 40 4.0 3.0 NaN 3.0 ADDVALUE 50 5.0 5.0 NaN 5.0 ADDVALUE";
const WE: &str = r"NEWGTS 'w' RENAME 10 NaN NaN 5 1.0 ADDVALUE 20 NaN NaN 6 2.0 ADDVALUE 40 NaN NaN 8 3.0 ADDVALUE 50 NaN NaN 12 5.0 ADDVALUE";
const WP: &str = r"NEWGTS 'w' RENAME 10 NaN NaN 5 1.0 ADDVALUE 20 NaN NaN NaN 2.0 ADDVALUE 40 NaN NaN 8 3.0 ADDVALUE 50 NaN NaN 9 5.0 ADDVALUE";
const S: &str = r"NEWGTS 's' RENAME 10 NaN NaN NaN 'a' ADDVALUE 20 NaN NaN NaN 'b' ADDVALUE 40 NaN NaN NaN 'c' ADDVALUE";

/// The script of a template, its `@NAME` placeholders replaced by the series above.
fn expand(template: &str) -> String {
    template
        .replace("@U6", U6)
        .replace("@U4", U4)
        .replace("@UL", UL)
        .replace("@V4", V4)
        .replace("@V3", V3)
        .replace("@WL", WL)
        .replace("@WE", WE)
        .replace("@WP", WP)
        .replace("@G", G)
        .replace("@D", D)
        .replace("@S", S)
}

/// The stack left by `script`, top first, as the JSON array of the Warp 10 exec endpoint,
/// or the error message.
fn stack_json(script: &str) -> Result<String, String> {
    let mut stack = test_stack();
    stack
        .exec_checked(&format!("{script} DEPTH ->LIST REVERSE ->JSON"))
        .map_err(|err| err.to_string())?;
    match stack.pop().unwrap() {
        Value::String(json) => Ok(json.to_string()),
        other => panic!("not a string: {other:?}"),
    }
}

/// Check every case, reporting all the mismatches at once.
fn check(cases: &[(&str, Result<&str, &str>)]) {
    let mut failures = Vec::new();
    for (template, expected) in cases {
        let script = expand(template);
        match (expected, stack_json(&script)) {
            (Ok(json), Ok(actual)) if actual == *json => {}
            (Err(message), Err(actual)) if actual.contains(message) => {}
            (expected, actual) => failures.push(format!(
                "{template}\n  expected {expected:?}\n  actual   {actual:?}"
            )),
        }
    }
    assert!(
        failures.is_empty(),
        "{} failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

